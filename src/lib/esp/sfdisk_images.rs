//! Disk images that sfdisk partitioned, as the bytes of them that PartitionTable::read reads:
//! LBA 0 and, on a GPT disk, the primary GPT header and its entry array. Their CRC32s are
//! sfdisk's, not the code's under test.

/// The first `length` bytes of a disk image of `block_size`-byte logical blocks: zero but for
/// the runs, each a byte offset and the bytes there.
pub(super) struct SfdiskImage {
    pub(super) block_size: u32,
    pub(super) length: usize,
    pub(super) runs: &'static [(usize, &'static [u8])],
}

